export function isKnownRoute(rawPath) {
  if (typeof rawPath !== 'string' || !rawPath.startsWith('/')) return false;
  const path = rawPath === '/' ? '/' : rawPath.replace(/\/+$/, '');
  const segments = path.split('/');
  return PROXY_ROUTES.some((route) => {
    const pattern = route.split('/');
    return pattern.length === segments.length && pattern.every((part, i) =>
      /^\[[^/]+\]$/.test(part) ? Boolean(segments[i]) : part === segments[i]);
  });
}
