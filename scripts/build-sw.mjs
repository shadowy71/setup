#!/usr/bin/env node
/**
 * Build `public/timetable/sw.js` from `lib/timetable/sw-entry.mjs`.
 *
 * A service worker has to be one classic script: it cannot import an ESM
 * module that the Next build has emitted into a hashed chunk, and it must not
 * import anything server-only. So the policy and the worker are written as
 * normal modules under `lib/timetable/` (unit-testable, importable from the
 * client for their constants) and bundled down to a single self-contained file
 * with esbuild — the same tool the contrast audit and the sign-out check
 * already use.
 *
 *   node scripts/build-sw.mjs            write the worker
 *   node scripts/build-sw.mjs --check    fail if the committed worker is stale
 *
 * `--check` is wired into `npm run verify` so the shipped worker can never
 * drift from the source that is tested.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';

// scripts/build-sw.mjs sits one level below the repository root.
const root = path.resolve(import.meta.dirname, '..');
const entry = path.join(root, 'lib/timetable/sw-entry.mjs');
const output = path.join(root, 'public/timetable/sw.js');
const check = process.argv.includes('--check');

const BANNER = `/* Campus+ timetable service worker — GENERATED by scripts/build-sw.mjs.
   Edit lib/timetable/sw-entry.mjs or lib/timetable/sw-policy.js instead, then
   run: npm run sw:bundle */`;

// `write: false` always: the text is compared in memory first, so a rebuild
// that changes nothing does not touch the file (and does not dirty a tree).
const result = await build({
  entryPoints: [entry],
  outfile: output,
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  platform: 'browser',
  minify: false,
  legalComments: 'none',
  banner: { js: BANNER },
  alias: { '@': root },
  logLevel: 'silent',
  write: false,
});

if (result.errors?.length) {
  for (const error of result.errors) console.error(`sw bundle: ${error.text}`);
  process.exit(1);
}

const generated = result.outputFiles.find((file) => path.resolve(file.path) === output)?.text;
if (!generated) {
  console.error('sw bundle: esbuild produced no output for public/timetable/sw.js');
  process.exit(1);
}

const committed = await readFile(output, 'utf8').catch(() => null);

if (check) {
  if (committed === null) {
    console.error('sw:check — public/timetable/sw.js is missing. Run: npm run sw:bundle');
    process.exit(1);
  }
  if (committed !== generated) {
    console.error(
      'sw:check — public/timetable/sw.js is out of date with lib/timetable/sw-entry.mjs.\n' +
        'Run: npm run sw:bundle',
    );
    process.exit(1);
  }
  console.log(`sw:check ✓ public/timetable/sw.js is current (${(Buffer.byteLength(generated) / 1024).toFixed(1)} kB)`);
  process.exit(0);
}

await mkdir(path.dirname(output), { recursive: true });

if (committed === generated) {
  console.log(`sw:bundle ✓ public/timetable/sw.js already current (${(Buffer.byteLength(generated) / 1024).toFixed(1)} kB)`);
  process.exit(0);
}

await writeFile(output, generated);
console.log(`sw:bundle → public/timetable/sw.js (${(Buffer.byteLength(generated) / 1024).toFixed(1)} kB)`);
