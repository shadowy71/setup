import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

import { GET as manifestGET } from '@/app/timetable/manifest/[division]/route';
import { GET as snapshotGET } from '@/app/api/timetable/[division]/route';
import { DIVISIONS } from '@/lib/constants';
import {
  TIMETABLE_APP_ID_PREFIX,
  TIMETABLE_CANVAS_COLOR,
  TIMETABLE_SCOPE,
  batchAppName,
  batchName,
  batchShortName,
  describeBatch,
  installLabel,
  listBatches,
  listDivisionLetters,
} from '@/lib/timetable/batch';
import { getDivisionTimetable } from '@/lib/timetable';
import { buildSnapshot, validateSnapshot } from '@/lib/timetable/offline';

/**
 * Batch identity, the per-batch manifest and the offline data route.
 *
 * The whole installable feature hangs on one property: a batch has exactly one
 * identity, and that identity is the division letter. If the manifest `id` were
 * derived from the display label, or two divisions shared a `start_url`, every
 * install would collide into one app and "Add FY IT-A" would silently open
 * somebody else's timetable. So the tests below go through *all eighteen*
 * divisions rather than sampling one.
 *
 * The PNG checks are deliberately shallow — "is this a real image of the right
 * size, at a path the manifest actually points at" — because the artwork is
 * generated by `npm run brand:timetable-icons` from `logo.jpeg` and reviewed by
 * eye, not asserted for taste here.
 */

const ROOT = process.cwd();
const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8');

function manifestFor(division) {
  return manifestGET(new Request(`http://campus.test/timetable/manifest/${division}`), {
    params: Promise.resolve({ division }),
  });
}

function snapshotFor(division) {
  return snapshotGET(new Request(`http://campus.test/api/timetable/${division}`), {
    params: Promise.resolve({ division }),
  });
}

describe('batch identity', () => {
  it('describes every division with a stable, letter-derived identity', () => {
    const batches = listBatches();
    expect(batches.map((batch) => batch.division)).toEqual(DIVISIONS);
    expect(listDivisionLetters()).toEqual(DIVISIONS);

    for (const batch of batches) {
      expect(batch.slug).toBe(batch.division.toLowerCase());
      expect(batch.href).toBe(`/timetable/${batch.slug}`);
      expect(batch.apiUrl).toBe(`/api/timetable/${batch.slug}`);
      expect(batch.manifestUrl).toBe(`/timetable/manifest/${batch.slug}`);
      expect(batch.appId).toBe(`${TIMETABLE_APP_ID_PREFIX}-${batch.slug}`);
      // No query parameters anywhere: a launch URL must not depend on one.
      expect(batch.href).not.toContain('?');
    }
  });

  it('gives every batch a unique id, start url and short name', () => {
    const batches = listBatches();
    const unique = (pick) => new Set(batches.map(pick)).size;
    expect(unique((batch) => batch.appId)).toBe(DIVISIONS.length);
    expect(unique((batch) => batch.href)).toBe(DIVISIONS.length);
    // `O · IT` and `P · IT` differ even though the branch label does not.
    expect(unique((batch) => batchShortName(batch.division))).toBe(DIVISIONS.length);
  });

  it('names a batch with its real label, never a demo name', () => {
    // O and P are the IT divisions in the source document.
    expect(batchName('O')).toBe('Division O (IT)');
    expect(batchName('j')).toBe('Division J (Comp)');
    expect(batchAppName('O')).toContain('Information Technology');
    // Where the source gives no expansion, none is invented.
    expect(batchAppName('N')).toBe('Division N (Comp-R) timetable');
    expect(batchAppName('I')).toBe('Division I (Civil RL) timetable');
    expect(batchShortName('O')).toBe('O · IT');
    expect(installLabel('O')).toBe('Add Division O (IT) timetable to Home Screen');
    expect(installLabel('nope')).toBe('Add this timetable to Home Screen');
  });

  it('refuses to invent a batch for anything that is not a division', () => {
    for (const value of [null, undefined, 42, '', '  ', 'S', 'AB', 'IT', 'first-year']) {
      expect(describeBatch(value), String(value)).toBeNull();
    }
    // Case and spacing are tolerated; nothing else is.
    expect(describeBatch(' o ').division).toBe('O');
    expect(describeBatch('O').division).toBe('O');
  });
});

describe('per-batch web app manifest', () => {
  it('launches the batch it belongs to, standalone, inside Campus+', async () => {
    for (const division of DIVISIONS) {
      const batch = describeBatch(division);
      const response = await manifestFor(batch.slug);
      expect(response.status, division).toBe(200);
      expect(response.headers.get('content-type')).toContain('application/manifest+json');

      const manifest = await response.json();
      expect(manifest.id, division).toBe(`${TIMETABLE_APP_ID_PREFIX}-${batch.slug}`);
      expect(manifest.start_url, division).toBe(batch.href);
      expect(manifest.scope, division).toBe(TIMETABLE_SCOPE);
      // The start URL has to be inside the scope, or the install is refused.
      expect(manifest.start_url.startsWith(manifest.scope)).toBe(true);
      expect(manifest.display, division).toBe('standalone');
      expect(manifest.name, division).toContain(`Division ${division}`);
      expect(manifest.short_name, division).toHaveLength(batchShortName(division).length);
      expect(manifest.short_name.length, division).toBeLessThanOrEqual(12);
      expect(manifest.prefer_related_applications, division).toBe(false);
      expect(manifest.theme_color, division).toBe(TIMETABLE_CANVAS_COLOR);
      expect(manifest.background_color, division).toBe(TIMETABLE_CANVAS_COLOR);
    }
  });

  it('declares the icons a launcher needs, and they exist on disk', async () => {
    const manifest = await (await manifestFor('o')).json();
    const purposes = manifest.icons.map((icon) => `${icon.sizes} ${icon.purpose}`);
    expect(purposes).toContain('192x192 any');
    expect(purposes).toContain('512x512 any');
    expect(purposes).toContain('192x192 maskable');
    expect(purposes).toContain('512x512 maskable');

    for (const icon of manifest.icons) {
      if (icon.src === '/apple-icon.png') continue; // generated by brand:icons
      const file = path.join(ROOT, 'public', icon.src.replace(/^\//, ''));
      expect(fs.existsSync(file), icon.src).toBe(true);
      const bytes = fs.readFileSync(file);
      // PNG signature + IHDR width/height, read directly: no image library.
      expect(bytes.subarray(1, 4).toString()).toBe('PNG');
      const width = bytes.readUInt32BE(16);
      const height = bytes.readUInt32BE(20);
      expect([width, height], icon.src).toEqual([Number(icon.sizes.split('x')[0]), Number(icon.sizes.split('x')[1])]);
      expect(bytes.length, icon.src).toBeLessThan(200 * 1024);
    }
  });

  it('is honest about being an unofficial student project', async () => {
    const manifest = await (await manifestFor('o')).json();
    expect(manifest.description).toContain('not an official PCCOE service');
    expect(manifest.description).toContain('SEM-I');
  });

  it('404s an unknown division instead of defaulting to one', async () => {
    const response = await manifestFor('s');
    expect(response.status).toBe(404);
  });

  it('is linked only from the division pages, through metadata', () => {
    const page = read('app/timetable/[division]/page.js');
    expect(page).toMatch(/manifest:\s*batch\s*\?\s*batch\.manifestUrl/);
    // …and iOS gets the batch name, because it reads these keys and not the manifest.
    expect(page).toMatch(/appleWebApp/);
    expect(page).toMatch(/statusBarStyle/);
  });

  it('is served under the public /timetable prefix, so no proxy change is needed', () => {
    const proxy = read('proxy.js');
    const publicPaths = /PUBLIC_PATHS = \[([^\]]*)\]/.exec(proxy)?.[1] ?? '';
    expect(publicPaths).toContain("'/timetable'");
    expect(read('app/timetable/manifest/[division]/route.js')).not.toMatch(/getCurrentUser|getServerClient|cookies\(\)/);
  });
});

describe('offline snapshot route', () => {
  it('returns each batch its own real timetable, validated by the same contract the browser uses', async () => {
    for (const division of DIVISIONS) {
      const response = await snapshotGET(new Request(`http://campus.test/api/timetable/${division.toLowerCase()}`), {
        params: Promise.resolve({ division }),
      });
      expect(response.status, division).toBe(200);
      const body = await response.json();
      expect(body.ok, division).toBe(true);

      const validated = validateSnapshot(body.snapshot, { expectDivision: division });
      expect(validated.ok, division).toBe(true);

      // The payload is the page's own view model, not a paraphrase of it.
      const live = getDivisionTimetable(division);
      const expected = buildSnapshot({ ...live, generatedAt: body.snapshot.generatedAt });
      expect(validated.snapshot.days, division).toEqual(expected.days);
      expect(validated.snapshot.checksum, division).toBe(expected.checksum);
      expect(validated.snapshot.eventCount, division).toBeGreaterThan(0);
      expect(validated.stale, division).toBe(false);
    }
  });

  it('separates Monday from Friday and one batch from another', async () => {
    const [o, j] = await Promise.all([
      (await snapshotFor('o')).json(),
      (await snapshotFor('j')).json(),
    ]);
    const days = (payload) => payload.snapshot.days.map((day) => day.events.map((event) => event.lines.join('|')).join(';'));
    const oDays = days(o);
    const jDays = days(j);

    // Within a batch, the five weekdays are five different days.
    expect(new Set(oDays).size).toBe(5);
    // Between batches, nothing collides: the checksum is the payload.
    expect(o.snapshot.checksum).not.toBe(j.snapshot.checksum);
    expect(oDays).not.toEqual(jDays);
  });

  it('is cacheable and public, and carries no user data', async () => {
    const response = await snapshotFor('o');
    expect(response.headers.get('cache-control')).toContain('public');
    expect(response.headers.get('cache-control')).not.toMatch(/private|cookie/i);
    expect(response.headers.get('vary')).not.toMatch(/cookie/i);
    // The ETag is the checksum, so an unchanged week is a 304.
    const body = await response.json();
    expect(response.headers.get('etag')).toContain(body.snapshot.checksum);

    const text = JSON.stringify(body);
    expect(text).not.toMatch(/token|secret|password|cookie|authorization/i);
  });

  it('404s an unknown division', async () => {
    const response = await snapshotFor('s');
    expect(response.status).toBe(404);
    expect(await response.json()).toEqual({ ok: false, error: 'division-not-found' });
  });

  it('generates exactly the eighteen known letters, lowercase, and nothing else', async () => {
    const route = read('app/api/timetable/[division]/route.js');
    expect(route).toMatch(/export const dynamicParams = false/);
    const { generateStaticParams } = await import('@/app/api/timetable/[division]/route');
    expect(generateStaticParams()).toEqual(DIVISIONS.map((division) => ({ division: division.toLowerCase() })));
  });
});
